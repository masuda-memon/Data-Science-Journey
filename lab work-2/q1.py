'''Q1. Demonstrate different formatting options in print()
Question: Write a program to demonstrate different formatting options in print():
1. Use sep to separate values with a custom character.
2. Use end to customize what appears at the end of a print statement.'''

print("Hello","How are youu!", sep="\n")
print("Welcome", "to", "Pyton", sep="-")
print("Hello","I am Masuda", end="*")
print("Hello", end=" ")
